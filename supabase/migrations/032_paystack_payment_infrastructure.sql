  ON public.invitations (payment_status)
  WHERE payment_status = 'unpaid';

-- ── 5. RLS — organizer_payment_settings ───────────────────────

ALTER TABLE public.organizer_payment_settings ENABLE ROW LEVEL SECURITY;

-- Organisers manage their own settings only
CREATE POLICY "Organisers manage their own payment settings"
  ON public.organizer_payment_settings FOR ALL
  USING (organizer_id = auth.uid())
  WITH CHECK (organizer_id = auth.uid());

-- ── 6. RLS — payments ─────────────────────────────────────────

ALTER TABLE public.payments ENABLE ROW LEVEL SECURITY;

-- Organisers can read payments for events they own
CREATE POLICY "Organisers can read payments for their events"
  ON public.payments FOR SELECT
  USING (
    EXISTS (
      SELECT 1 FROM public.events e
      WHERE e.id = payments.event_id
        AND e.organizer_id = auth.uid()
    )
  );

-- Co-hosts with any role can read payment data for events they are members of
CREATE POLICY "Members can read payments for co-hosted events"
  ON public.payments FOR SELECT
  USING (
    EXISTS (
      SELECT 1 FROM public.event_members em
      WHERE em.event_id = payments.event_id
        AND em.member_id = auth.uid()
    )
  );

-- No direct INSERT/UPDATE from authenticated users — all writes go through
-- the webhook handler and payment actions which use the admin (service-role) client.

-- ── 7. updated_at triggers ────────────────────────────────────

-- Reuse the pattern if a generic updated_at trigger function exists,
-- otherwise create a local one scoped to these two tables.

DO $$
BEGIN
  -- Create function only if it doesn't already exist (may exist from earlier migrations)
  IF NOT EXISTS (
    SELECT 1 FROM pg_proc p
    JOIN pg_namespace n ON n.oid = p.pronamespace
    WHERE n.nspname = 'public'
      AND p.proname = 'set_updated_at'
  ) THEN
    EXECUTE $func$
      CREATE OR REPLACE FUNCTION public.set_updated_at()
      RETURNS TRIGGER LANGUAGE plpgsql AS $$
      BEGIN
        NEW.updated_at = now();
        RETURN NEW;
      END;
      $$;
    $func$;
  END IF;
END;
$$;

CREATE TRIGGER payments_updated_at
  BEFORE UPDATE ON public.payments
  FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();

CREATE TRIGGER organizer_payment_settings_updated_at
  BEFORE UPDATE ON public.organizer_payment_settings
  FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();
