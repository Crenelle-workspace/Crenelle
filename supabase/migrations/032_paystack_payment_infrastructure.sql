-- ── 1. organizer_payment_settings ────────────────────────────

CREATE TABLE IF NOT EXISTS public.organizer_payment_settings (
  id                      uuid          DEFAULT gen_random_uuid() PRIMARY KEY,
  organizer_id            uuid          NOT NULL UNIQUE
                                        REFERENCES auth.users(id) ON DELETE CASCADE,
  -- Paystack subaccount (null until organiser connects their bank)
  paystack_subaccount_code text,        -- e.g. ACCT_xxxxxxxxxxxxxxxx
  -- Bank details (stored after account resolution)
  bank_name               text,
  bank_code               text,         -- Paystack bank code, e.g. '058' for GTBank
  account_number          text,
  account_name            text,         -- resolved display name from Paystack
  -- Status
  is_verified             boolean       NOT NULL DEFAULT false,
  -- Fee split: Crenelle's platform commission percentage
  -- Organiser receives (100 - platform_fee_percent)% of net amount
  platform_fee_percent    numeric(5,2)  NOT NULL DEFAULT 5.00
                                        CHECK (platform_fee_percent >= 0 AND platform_fee_percent <= 100),
  connected_at            timestamptz,
  created_at              timestamptz   NOT NULL DEFAULT now(),
  updated_at              timestamptz   NOT NULL DEFAULT now()
);

COMMENT ON TABLE public.organizer_payment_settings IS
  'Stores each organiser''s Paystack subaccount and bank details for split payment settlement.';

COMMENT ON COLUMN public.organizer_payment_settings.paystack_subaccount_code IS
  'Paystack subaccount code (ACCT_xxx). Null until the organiser connects their bank account.';

COMMENT ON COLUMN public.organizer_payment_settings.platform_fee_percent IS
  'Crenelle''s commission percentage. Organiser receives (100 - this)% of each transaction''s net amount.';

-- ── 2. payments ───────────────────────────────────────────────

-- payment_status enum-like domain via CHECK (avoids ENUM migration complexity)
CREATE TABLE IF NOT EXISTS public.payments (
  id                      uuid          DEFAULT gen_random_uuid() PRIMARY KEY,
  event_id                uuid          NOT NULL
                                        REFERENCES public.events(id) ON DELETE RESTRICT,
  attendee_id             uuid
                                        REFERENCES public.attendees(id) ON DELETE SET NULL,
  ticket_tier_id          uuid
                                        REFERENCES public.ticket_tiers(id) ON DELETE SET NULL,
  -- Paystack identifiers
  paystack_reference      text          NOT NULL UNIQUE,  -- our generated reference (CRN-xxx)
  paystack_transaction_id bigint,                         -- Paystack's internal transaction ID
  -- Amounts — all stored in kobo (NGN × 100)
  amount_kobo             integer       NOT NULL CHECK (amount_kobo > 0),
  platform_fee_kobo       integer       CHECK (platform_fee_kobo >= 0),
  organiser_amount_kobo   integer       CHECK (organiser_amount_kobo >= 0),
  currency                text          NOT NULL DEFAULT 'NGN',
  -- Status lifecycle
  status                  text          NOT NULL DEFAULT 'pending'
                                        CHECK (status IN ('pending', 'paid', 'failed', 'refunded', 'abandoned')),
  -- Payer info (captured at point of payment)
  payer_email             text          NOT NULL,
  payer_name              text,
  -- Paystack channel: card, bank, ussd, bank_transfer, qr
  paystack_channel        text,
  -- Flexible metadata: tier name, event name, etc. (for receipts & dispute evidence)
  metadata                jsonb,
  -- Timestamps
  webhook_received_at     timestamptz,
  paid_at                 timestamptz,
  created_at              timestamptz   NOT NULL DEFAULT now(),
  updated_at              timestamptz   NOT NULL DEFAULT now()
);

COMMENT ON TABLE public.payments IS
  'Full audit trail for every Paystack transaction. One row per payment attempt.';

COMMENT ON COLUMN public.payments.paystack_reference IS
  'Unique reference generated by Crenelle (format: CRN-{eventId8}-{timestamp}). Sent to Paystack on initialize.';

COMMENT ON COLUMN public.payments.amount_kobo IS
  'Total amount the guest was charged, in kobo (NGN amount × 100). Verified against Paystack webhook.';

-- ── 3. Extend invitations table ───────────────────────────────

-- payment_status on the invitation (denormalised for fast dashboard queries)
ALTER TABLE public.invitations
  ADD COLUMN IF NOT EXISTS payment_status text DEFAULT 'unpaid'
    CHECK (payment_status IN ('unpaid', 'paid', 'refunded', 'failed')),
  ADD COLUMN IF NOT EXISTS amount_paid_kobo integer,
  ADD COLUMN IF NOT EXISTS paid_at timestamptz;

COMMENT ON COLUMN public.invitations.payment_status IS
  'Denormalised payment state for dashboard display. Source of truth is the payments table.';

-- ── 4. Indexes ────────────────────────────────────────────────

-- organizer_payment_settings
CREATE INDEX IF NOT EXISTS organizer_payment_settings_organizer_id_idx
  ON public.organizer_payment_settings (organizer_id);

